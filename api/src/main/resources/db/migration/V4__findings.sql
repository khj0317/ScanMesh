-- 엔진이 보낸 발견 항목을 그대로 남긴다. 엔진 간 중복은 저장할 때 지우지 않고, 보여 줄 때 fingerprint로 묶는다.
-- 그래야 어느 엔진이 무엇을 찾았는지가 사라지지 않는다
create table findings (
    id             bigint generated by default as identity primary key,
    -- 점검별로 모아 보기 위해 작업을 거치지 않고 바로 연결한다
    scan_id        bigint        not null references scans (id) on delete cascade,
    task_id        bigint        not null references scan_tasks (id) on delete cascade,
    engine         varchar(20)   not null,
    rule_id        varchar(300)  not null,
    title          varchar(300)  not null,
    severity       varchar(10)   not null,
    cwe_id         int,
    owasp_category varchar(60),
    url            varchar(2048) not null,
    -- 같은 URL 안에서 위치를 나누는 이름 (쿠키·파라미터)
    param          varchar(200),
    evidence       varchar(2000),
    remediation    varchar(4000),
    -- 엔진이 달라도 같은 문제면 같은 값 (SHA-256 16진수 64자)
    fingerprint    varchar(64)   not null,
    created_at     timestamptz   not null
);

create index idx_findings_scan_fingerprint on findings (scan_id, fingerprint);
create index idx_findings_task on findings (task_id);

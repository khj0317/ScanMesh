create table targets (
    id                           bigint generated by default as identity primary key,
    member_id                    bigint        not null references members (id) on delete cascade,
    -- 점검을 시작할 주소. 정규화해서 저장한다 (소문자 호스트, 기본 포트 생략, 쿼리·조각 제거)
    base_url                     varchar(2048) not null,
    -- 소유 인증 단위. IDN은 퓨니코드(xn--)로 바꿔 저장한다
    host                         varchar(253)  not null,
    verification_method          varchar(20)   not null,
    -- 사용자에게 다시 보여 줘야 하므로 해시하지 않는다. 비밀 값이 아니라 소유 확인용 표식이다
    verification_token           varchar(64)   not null,
    -- null이면 아직 인증 전이라 점검을 요청할 수 없다
    verified_at                  timestamptz,
    -- 인증 확인 요청마다 서버가 외부로 DNS·HTTP 요청을 보내므로 간격을 제한하는 데 쓴다
    last_verification_attempt_at timestamptz,
    created_at                   timestamptz   not null,
    updated_at                   timestamptz   not null,
    -- 회원별 목록 조회에도 이 유일 인덱스를 쓴다
    constraint uk_targets_member_host unique (member_id, host)
);

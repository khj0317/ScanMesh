create table workers (
    id           bigint generated by default as identity primary key,
    name         varchar(50) not null,
    -- LIGHT: 자체 규칙·Nuclei, HEAVY: ZAP
    kind         varchar(10) not null,
    -- 원문 대신 SHA-256 해시(16진수 64자)만 저장한다. 원문은 등록할 때 한 번만 보여 준다
    token_hash   varchar(64) not null,
    last_seen_at timestamptz,
    created_at   timestamptz not null,
    updated_at   timestamptz not null,
    constraint uk_workers_token_hash unique (token_hash)
);

-- 점검 상태는 저장하지 않고 scan_tasks의 상태에서 계산한다
create table scans (
    id           bigint generated by default as identity primary key,
    target_id    bigint      not null references targets (id) on delete cascade,
    requested_by bigint      not null references members (id) on delete cascade,
    requested_at timestamptz not null,
    -- 마지막 작업이 끝난 시각. 목록에서 작업을 모두 읽지 않고 끝났는지 알 수 있게 남긴다
    finished_at  timestamptz,
    created_at   timestamptz not null,
    updated_at   timestamptz not null
);

create index idx_scans_target on scans (target_id, id desc);

create table scan_tasks (
    id               bigint generated by default as identity primary key,
    scan_id          bigint      not null references scans (id) on delete cascade,
    engine           varchar(20) not null,
    status           varchar(20) not null,
    -- 워커가 가져갈 때마다 1 늘린다. max_attempts에 닿으면 더 재시도하지 않는다
    attempt          int         not null default 0,
    max_attempts     int         not null,
    worker_id        bigint      references workers (id) on delete set null,
    -- 이 시각까지 하트비트가 없으면 워커가 죽은 것으로 보고 다시 큐에 넣는다
    lease_until      timestamptz,
    cancel_requested boolean     not null default false,
    progress         int         not null default 0,
    error_message    varchar(1000),
    started_at       timestamptz,
    finished_at      timestamptz,
    created_at       timestamptz not null,
    updated_at       timestamptz not null,
    constraint ck_scan_tasks_progress check (progress between 0 and 100)
);

create index idx_scan_tasks_scan on scan_tasks (scan_id);
-- 워커가 가져갈 작업 찾기: 대기 중인 작업만 담은 작은 인덱스
create index idx_scan_tasks_queued on scan_tasks (engine, id) where status = 'QUEUED';
-- 임대가 끝난 작업 찾기
create index idx_scan_tasks_running_lease on scan_tasks (lease_until) where status = 'RUNNING';
